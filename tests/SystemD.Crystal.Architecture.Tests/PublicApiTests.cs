// Spec 015 R3.3 (task T9) — the public API baseline. From 1.0 the public surface follows semantic versioning, so any
// change to it must be deliberate: this test lists every public type and member of SystemD.Crystal, one line each, and
// compares the list with PublicApi.txt beside this file. A difference fails the build, names every line added and
// removed, and writes PublicApi.received.txt next to the baseline; updating the baseline (copy the received file over
// it) is done in the same commit as the API change and its CHANGELOG line.

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.CompilerServices;
using Xunit;

namespace SystemD.Crystal.Architecture.Tests;

public sealed class PublicApiTests
{
    private static readonly Assembly Crystal = typeof(global::SystemD.Crystal.CrystalVersion).Assembly;

    [Fact]
    public void PublicApi_MatchesTheBaseline()
    {
        var baselinePath = Path.Combine(SourceDirectory(), "PublicApi.txt");
        var receivedPath = Path.Combine(SourceDirectory(), "PublicApi.received.txt");
        var actual = PublicApi.Describe(Crystal);

        var expected = File.Exists(baselinePath)
            ? File.ReadAllLines(baselinePath).Where(l => l.Length > 0 && !l.StartsWith('#')).ToList()
            : [];

        var added = actual.Except(expected, StringComparer.Ordinal).ToList();
        var removed = expected.Except(actual, StringComparer.Ordinal).ToList();
        if (added.Count == 0 && removed.Count == 0)
        {
            if (File.Exists(receivedPath))
            {
                File.Delete(receivedPath);
            }

            return;
        }

        File.WriteAllLines(receivedPath, PublicApi.Header.Concat(actual));
        Assert.Fail(
            $"The public API differs from {Path.GetFileName(baselinePath)} (spec 015 R3.3). If the change is intended, copy " +
            $"{Path.GetFileName(receivedPath)} over it in the same commit as the change and its CHANGELOG line.\n" +
            $"Added ({added.Count}):" + string.Concat(added.Take(60).Select(l => "\n  + " + l)) +
            $"\nRemoved ({removed.Count}):" + string.Concat(removed.Take(60).Select(l => "\n  - " + l)));
    }

    [Fact]
    public void PublicApi_Describe_SeesASignatureChange()
    {
        // The guard's own check: a description that differs in one parameter's nullability is a different line.
        var lines = PublicApi.Describe(Crystal);
        Assert.NotEmpty(lines);
        Assert.Contains(lines, l => l.StartsWith("type SystemD.Crystal.CrystalStore ", StringComparison.Ordinal));
        Assert.Contains(lines, l => l.Contains("SystemD.Crystal.CrystalStore::static Open(", StringComparison.Ordinal));
        Assert.Equal(lines.Count, lines.Distinct(StringComparer.Ordinal).Count());
    }

    private static string SourceDirectory([CallerFilePath] string path = "") => Path.GetDirectoryName(path)!;
}

/// <summary>Describes an assembly's public surface as sorted, stable lines.</summary>
internal static class PublicApi
{
    public static readonly string[] Header =
    [
        "# The public API of SystemD.Crystal (spec 015 R3.3), one line per public type and member. Generated by",
        "# PublicApiTests; change it only with an intended API change, in the same commit as that change.",
    ];

    private const BindingFlags Declared =
        BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;

    private static readonly NullabilityInfoContext Nullability = new();

    public static List<string> Describe(Assembly assembly)
    {
        var lines = new List<string>();
        foreach (var type in assembly.GetExportedTypes())
        {
            lines.Add(DescribeType(type));
            foreach (var member in type.GetMembers(Declared).Where(m => IsVisible(m) && !IsCompilerGenerated(m)))
            {
                if (Describe(type, member) is { } line)
                {
                    lines.Add(line);
                }
            }
        }

        lines.Sort(StringComparer.Ordinal);
        return lines;
    }

    /// <summary>A record's generated plumbing (<c>&lt;Clone&gt;$</c>, <c>EqualityContract</c>, <c>PrintMembers</c>): not callable API.</summary>
    private static bool IsCompilerGenerated(MemberInfo member) =>
        member.Name.StartsWith('<') || member.Name is "EqualityContract" or "PrintMembers";

    private static bool IsVisible(MemberInfo member) => member switch
    {
        MethodBase m => (m.IsPublic || m.IsFamily || m.IsFamilyOrAssembly) && !m.IsSpecialName || m is ConstructorInfo { IsPublic: true } or ConstructorInfo { IsFamily: true },
        FieldInfo f => (f.IsPublic || f.IsFamily || f.IsFamilyOrAssembly) && !f.IsSpecialName,
        PropertyInfo p => p.GetAccessors(nonPublic: true).Any(a => a.IsPublic || a.IsFamily || a.IsFamilyOrAssembly),
        EventInfo e => e.AddMethod is { } add && (add.IsPublic || add.IsFamily || add.IsFamilyOrAssembly),
        _ => false, // nested types are listed as types of their own
    };

    private static string DescribeType(Type type)
    {
        var kind = type.IsEnum ? "enum"
            : type.IsInterface ? "interface"
            : typeof(Delegate).IsAssignableFrom(type) ? "delegate"
            : type.IsValueType ? (type.GetMethod("<Clone>$") is not null || IsRecordStruct(type) ? "record struct" : "struct")
            : type.GetMethod("<Clone>$") is not null ? "record"
            : "class";
        var modifiers = new List<string>();
        if (type.IsAbstract && type.IsSealed)
        {
            modifiers.Add("static");
        }
        else if (type.IsSealed && !type.IsValueType && !type.IsEnum && kind is not "delegate")
        {
            modifiers.Add("sealed");
        }
        else if (type.IsAbstract && !type.IsInterface)
        {
            modifiers.Add("abstract");
        }

        if (type.IsValueType && type.GetCustomAttributes().Any(a => a.GetType().Name == "IsReadOnlyAttribute"))
        {
            modifiers.Add("readonly");
        }

        var bases = new List<string>();
        if (type.BaseType is { } baseType && baseType != typeof(object) && baseType != typeof(ValueType) && baseType != typeof(Enum)
            && baseType != typeof(MulticastDelegate))
        {
            bases.Add(Name(baseType));
        }

        bases.AddRange(type.GetInterfaces().Where(i => i.IsPublic || i.IsNestedPublic).Select(Name).Order(StringComparer.Ordinal));
        if (type.IsEnum)
        {
            bases.Add(Name(Enum.GetUnderlyingType(type)));
        }

        return $"type {Name(type)} {kind}" + (modifiers.Count > 0 ? " " + string.Join(" ", modifiers) : "") +
            (bases.Count > 0 ? " : " + string.Join(", ", bases) : "");
    }

    private static bool IsRecordStruct(Type type) =>
        type.GetMethod("PrintMembers", BindingFlags.NonPublic | BindingFlags.Instance) is not null;

    private static string? Describe(Type owner, MemberInfo member)
    {
        var prefix = $"{Name(owner)}::";
        switch (member)
        {
            case ConstructorInfo c:
                return $"{prefix}.ctor({Parameters(c)})";
            case MethodInfo m:
                var generic = m.IsGenericMethodDefinition ? "<" + string.Join(", ", m.GetGenericArguments().Select(a => a.Name)) + ">" : "";
                return $"{prefix}{Modifiers(m)}{m.Name}{generic}({Parameters(m)}) : {Annotated(m.ReturnParameter)}";
            case PropertyInfo p:
                var accessors = new List<string>();
                if (p.GetMethod is { } get && (get.IsPublic || get.IsFamily))
                {
                    accessors.Add("get;");
                }

                if (p.SetMethod is { } set && (set.IsPublic || set.IsFamily))
                {
                    var init = set.ReturnParameter.GetRequiredCustomModifiers().Any(t => t.FullName == "System.Runtime.CompilerServices.IsExternalInit");
                    accessors.Add(init ? "init;" : "set;");
                }

                var index = p.GetIndexParameters();
                var name = index.Length > 0 ? $"this[{string.Join(", ", index.Select(i => $"{Name(i.ParameterType)} {i.Name}"))}]" : p.Name;
                var isStatic = (p.GetMethod ?? p.SetMethod)!.IsStatic ? "static " : "";
                var required = p.GetCustomAttributes().Any(a => a.GetType().Name == "RequiredMemberAttribute") ? "required " : "";
                return $"{prefix}{isStatic}{required}{name} {{ {string.Join(" ", accessors)} }} : {Annotated(p)}";
            case FieldInfo f:
                if (owner.IsEnum)
                {
                    return f.IsStatic ? $"{prefix}{f.Name} = {Convert.ToInt64(f.GetRawConstantValue(), System.Globalization.CultureInfo.InvariantCulture)}" : null;
                }

                var kind = f.IsLiteral ? $"const {Annotated(f)} = {Literal(f.GetRawConstantValue())}"
                    : (f.IsStatic ? "static " : "") + (f.IsInitOnly ? "readonly " : "") + Annotated(f);
                return $"{prefix}{f.Name} : {kind}";
            case EventInfo e:
                return $"{prefix}event {e.Name} : {Name(e.EventHandlerType!)}";
            default:
                return null;
        }
    }

    private static string Modifiers(MethodInfo m) =>
        (m.IsStatic ? "static " : "") + (m.IsAbstract ? "abstract " : m.IsVirtual && !m.IsFinal && m.DeclaringType is { IsSealed: false } ? "virtual " : "");

    private static string Parameters(MethodBase method) =>
        string.Join(", ", method.GetParameters().Select(p =>
        {
            var modifier = p.IsOut ? "out " : p.ParameterType.IsByRef ? (p.IsIn ? "in " : "ref ") : "";
            var isParams = p.GetCustomAttributes().Any(a => a.GetType().Name is "ParamArrayAttribute" or "ParamCollectionAttribute") ? "params " : "";
            var optional = p.HasDefaultValue ? " = " + Literal(p.DefaultValue) : p.IsOptional ? " = default" : "";
            return $"{isParams}{modifier}{Annotated(p)} {p.Name}{optional}";
        }));

    private static string Annotated(ParameterInfo p) => Annotate(p.ParameterType.IsByRef ? p.ParameterType.GetElementType()! : p.ParameterType, SafeNullability(() => Nullability.Create(p)));

    private static string Annotated(PropertyInfo p) => Annotate(p.PropertyType, SafeNullability(() => Nullability.Create(p)));

    private static string Annotated(FieldInfo f) => Annotate(f.FieldType, SafeNullability(() => Nullability.Create(f)));

    private static NullabilityInfo? SafeNullability(Func<NullabilityInfo> create)
    {
        try
        {
            return create();
        }
        catch (Exception)
        {
            return null;
        }
    }

    private static string Annotate(Type type, NullabilityInfo? info)
    {
        var name = Name(type);
        var nullable = !type.IsValueType && info is { ReadState: NullabilityState.Nullable } or { WriteState: NullabilityState.Nullable };
        return nullable && !name.EndsWith('?') ? name + "?" : name;
    }

    private static string Literal(object? value) => value switch
    {
        null => "null",
        string s => "\"" + s + "\"",
        bool b => b ? "true" : "false",
        IFormattable f => f.ToString(null, System.Globalization.CultureInfo.InvariantCulture),
        _ => value.ToString() ?? "",
    };

    private static string Name(Type type)
    {
        if (type.IsByRef)
        {
            return Name(type.GetElementType()!);
        }

        if (type.IsArray)
        {
            return Name(type.GetElementType()!) + "[" + new string(',', type.GetArrayRank() - 1) + "]";
        }

        if (Nullable.GetUnderlyingType(type) is { } underlying)
        {
            return Name(underlying) + "?";
        }

        if (type.IsGenericParameter)
        {
            return type.Name;
        }

        var name = type.IsNested ? Name(type.DeclaringType!) + "." + type.Name : (type.Namespace is { } ns ? ns + "." : "") + type.Name;
        if (type.IsGenericType)
        {
            var tick = name.LastIndexOf('`');
            if (tick >= 0)
            {
                name = name[..tick];
            }

            name += "<" + string.Join(", ", type.GetGenericArguments().Select(Name)) + ">";
        }

        return name;
    }
}
